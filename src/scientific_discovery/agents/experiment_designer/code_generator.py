
import ast
import json
import ollama


MODEL_NAME = "gemma3:1b"

EXPERIMENT_SCHEMA = {
    "type": "object",
    "properties": {
        "title": {"type": "string"},
        "explanation": {"type": "string"},
        "observations": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "activity_level": {"type": "number"},
                    "glucose_reading": {"type": "number"}
                },
                "required": ["activity_level", "glucose_reading"]
            }
        },
        "assumptions": {
            "type": "array",
            "items": {"type": "string"}
        }
    },
    "required": [
        "title",
        "explanation",
        "observations",
        "assumptions"
    ]
}


def validate_experiment_code(code: str) -> None:
    """Validate the Python script generated by our trusted template."""

    if not code.strip():
        raise ValueError("Experiment code is empty.")

    if len(code.encode("utf-8")) > 20_000:
        raise ValueError("Experiment code exceeds the size limit.")

    try:
        tree = ast.parse(code)
    except SyntaxError as exc:
        raise ValueError(f"Invalid Python syntax: {exc}") from exc

    for node in ast.walk(tree):
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            raise ValueError("Imports are not allowed.")

        if isinstance(node, ast.Attribute):
            raise ValueError("Attribute access is not allowed.")

        if isinstance(node, ast.Name):
            if node.id.startswith("__") or node.id in {
                "eval", "exec", "compile", "open", "input",
                "__import__", "globals", "locals"
            }:
                raise ValueError(f"Blocked name: {node.id}")

        if isinstance(node, ast.Call):
            if not isinstance(node.func, ast.Name):
                raise ValueError("Only direct function calls are allowed.")

            if node.func.id not in {
                "print", "len", "sum", "min", "max", "round",
                "abs", "float", "int", "str", "list", "dict"
            }:
                raise ValueError(
                    f"Function '{node.func.id}' is not approved."
                )


def generate_experiment_code(
    hypothesis_details: dict,
    research_findings: list[str],
    critic_feedback: str = "",
    previous_code: str = ""
) -> dict:
    """Ask Gemma for experiment data and build Python code using a fixed template."""

    hypothesis = hypothesis_details.get("hypothesis", "")
    variables = hypothesis_details.get("variables", [])

    prompt = f"""
You are a scientific experiment planning assistant.

Hypothesis:
{hypothesis}

Variables:
{variables}

Research findings:
{research_findings}

Critic feedback:
{critic_feedback or "None"}

Previous experiment:
{previous_code or "None"}

Create a SMALL synthetic demonstration dataset.

Return:
1. A short experiment title.
2. A short explanation.
3. Exactly 3 to 5 observations.
4. Each observation must have:
   - activity_level: a number from 0 to 100
   - glucose_reading: a number from 50 to 250
5. A list of assumptions.

Important:
- All observations are synthetic demonstration data.
- Do not claim they represent real patients.
- Do not claim they prove the hypothesis.
- Do not invent scientific conclusions.
- If critic feedback exists, consider it in the experiment plan.
- Return only the requested structured JSON.
"""

    response = ollama.chat(
        model=MODEL_NAME,
        messages=[{"role": "user", "content": prompt}],
        format=EXPERIMENT_SCHEMA,
        options={
            "temperature": 0.1,
            "num_predict": 400
        }
    )

    raw_response = response.get("message", {}).get("content", "")

    try:
        result = json.loads(raw_response)
    except json.JSONDecodeError as exc:
        raise ValueError(
            f"Gemma returned invalid experiment JSON: {raw_response}"
        ) from exc

    observations = result.get("observations", [])

    if not 3 <= len(observations) <= 5:
        raise ValueError("Gemma must generate between 3 and 5 observations.")

    for observation in observations:
        activity = observation["activity_level"]
        glucose = observation["glucose_reading"]

        if not isinstance(activity, (int, float)) or isinstance(activity, bool):
            raise ValueError("Activity level must be numeric.")

        if not isinstance(glucose, (int, float)) or isinstance(glucose, bool):
            raise ValueError("Glucose reading must be numeric.")

        if not 0 <= activity <= 100:
            raise ValueError("Activity level is outside the allowed range.")

        if not 50 <= glucose <= 250:
            raise ValueError("Glucose reading is outside the allowed range.")

    # Construct executable Python ourselves, not with model-generated code.
    observations_literal = repr(observations)
    title_literal = repr(result.get("title", "Synthetic experiment"))

    code = f'''
# Synthetic demonstration experiment
# These values are not real patient observations.

observations = {observations_literal}

print("Experiment:", {title_literal})
print("Dataset type: Synthetic demonstration data")
print("Number of observations:", len(observations))

glucose_values = [
    observation["glucose_reading"]
    for observation in observations
]

for observation in observations:
    print(
        "Activity level:", observation["activity_level"],
        "Glucose reading:", observation["glucose_reading"]
    )

average_glucose = sum(glucose_values) / len(glucose_values)

print("Average glucose reading:", round(average_glucose, 2))
print("This demonstration does not validate the hypothesis.")
'''

    validate_experiment_code(code)

    return {
        "code": code,
        "explanation": result.get("explanation", ""),
        "assumptions": result.get("assumptions", []),
        "title": result.get("title", "Synthetic experiment")
    }
